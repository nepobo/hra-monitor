# frozen_string_literal: true

require "fileutils"
require "optparse"
require "uri"
require "yaml"

module HraMonitor
  ROOT = File.expand_path("..", __dir__)
  APPS_FILE = File.join(ROOT, "apps.yml")
  FILE_SD_DIR = File.join(ROOT, "prometheus", "file_sd")
  CHECKLIST = File.join(ROOT, "templates", "app", "CHECKLIST.md")

  module_function

  def load_registry
    data = YAML.load_file(APPS_FILE) || {}
    data["apps"] ||= {}
    data
  end

  def save_registry(data)
    header = <<~HEADER
      # Registry of monitored applications. Source of truth for scrape targets.
      # Add apps with `bin/add-app` or edit this file, then run `bin/render` and `bin/apply`.
      #
      # scrape.url is the stable HTTP(S) endpoint Prometheus will pull.
      # Web roles should use the public HTTPS host. Sidekiq roles should use
      # host:published-port (see templates/app/deploy.yml.snippet).
      # nodes are hosts that run node-exporter on :9100.

    HEADER
    File.write(APPS_FILE, header + YAML.dump(data).sub(/\A---\n/, ""))
  end

  def render!
    apps = load_registry.fetch("apps")
    FileUtils.mkdir_p(FILE_SD_DIR)

    rails = []
    nodes = []
    probes = []

    apps.each do |name, cfg|
      env = cfg["env"] || "production"

      Array(cfg["scrape"]).each do |entry|
        url = URI.parse(entry.fetch("url"))
        raise ArgumentError, "#{name}: scrape url must include a host: #{entry["url"]}" if url.host.nil?

        path = url.path.to_s.empty? ? "/metrics" : url.path
        port = url.port || (url.scheme == "https" ? 443 : 80)
        labels = {
          "app" => name,
          "env" => env,
          "role" => entry.dig("labels", "role") || entry["job"] || "web"
        }
        labels.merge!(stringify_keys(entry["labels"] || {}))
        labels["__scheme__"] = url.scheme || "http"
        labels["__metrics_path__"] = path

        rails << { "targets" => ["#{url.host}:#{port}"], "labels" => labels }
      end

      Array(cfg["nodes"]).each do |host|
        nodes << {
          "targets" => ["#{host_only(host)}:9100"],
          "labels" => { "app" => name, "env" => env }
        }
      end

      if cfg["healthcheck"]
        probes << {
          "targets" => [cfg["healthcheck"]],
          "labels" => { "app" => name, "env" => env }
        }
      end
    end

    nodes = nodes.uniq { |row| row["targets"] }

    write_sd("rails.yml", rails)
    write_sd("nodes.yml", nodes)
    write_sd("blackbox.yml", probes)

    {
      apps: apps.size,
      rails: rails.size,
      nodes: nodes.size,
      probes: probes.size
    }
  end

  def add_app!(options)
    raise ArgumentError, "--name is required" if options[:name].to_s.empty?

    data = load_registry
    name = options[:name]
    existing = data["apps"][name] || {}
    cfg = {
      "env" => options[:env] || existing["env"] || "production"
    }
    cfg["healthcheck"] = options[:health_url] if options[:health_url]
    cfg["healthcheck"] ||= existing["healthcheck"] if existing["healthcheck"]

    scrapes = options[:scrapes].any? ? options[:scrapes] : Array(existing["scrape"])
    cfg["scrape"] = scrapes if scrapes.any?

    nodes = options[:nodes].any? ? options[:nodes] : Array(existing["nodes"])
    cfg["nodes"] = nodes if nodes.any?

    data["apps"][name] = compact_cfg(cfg)
    save_registry(data)
    stats = render!
    checklist = File.read(CHECKLIST).gsub("__APP__", name).gsub("__ENV__", cfg["env"].to_s)

    { name: name, config: data["apps"][name], stats: stats, checklist: checklist }
  end

  def write_sd(filename, rows)
    path = File.join(FILE_SD_DIR, filename)
    payload = rows.empty? ? [] : rows
    File.write(path, <<~YAML)
      # Generated by bin/render from apps.yml. Do not edit by hand.
      #{YAML.dump(payload).sub(/\A---\n/, "")}
    YAML
  end

  def host_only(host)
    host.to_s.sub(%r{\Ahttps?://}i, "").split("/").first.split(":").first
  end

  def stringify_keys(hash)
    hash.each_with_object({}) { |(key, value), out| out[key.to_s] = value }
  end

  def compact_cfg(cfg)
    cfg.reject { |_key, value| value.nil? || (value.respond_to?(:empty?) && value.empty?) }
  end
end
